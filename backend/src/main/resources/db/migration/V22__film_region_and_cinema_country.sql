-- V22: where things are.
--
-- Two facts, one migration, because they are the same idea seen from two
-- sides. A cinema is in a country. A film was released into a country. The
-- seeder currently knows neither, which is why Jaipur advertises films that
-- only opened in the UK.
--
-- The word is territory: GB or IN, where a film was released. Not "regional",
-- which in Indian cinema means the non-Hindi language industries and is a
-- different axis entirely. The column below is named region because that is
-- what TMDB calls the parameter the data comes from.


-- --------------------------------------------------------------- countries

-- A lookup table rather than a CHECK on each column, for the same reason
-- currency, hall_class and seat_tier are lookup tables. Here it also pays for
-- itself twice over: two different tables constrain to this same domain, and
-- a CHECK repeated on two tables is two places to edit when a third market
-- arrives, which is how the two of them drift apart.
--
-- text with a length CHECK, not char(2). char is blank-padded in Postgres, so
-- a char(2) compared against a text parameter can surprise you at the edges,
-- and the project already settled this shape on currency(code).
--
-- display_name is here so the frontend has something to render that is not an
-- ISO code, and so the table is worth joining to rather than being a list of
-- allowed strings wearing a table costume.
--
-- Deliberately not folding currency or timezone in here. Both already live on
-- the cinema, where V17 put them, because they are facts about the building
-- and not about the country: London and Edinburgh share a currency, and a
-- country with two zones would make the column a lie. That is a separate
-- argument and not this migration's.
CREATE TABLE country (
    code         text PRIMARY KEY CHECK (char_length(code) = 2),
    display_name text NOT NULL
);

INSERT INTO country (code, display_name) VALUES
    ('GB', 'United Kingdom'),
    ('IN', 'India');


-- ----------------------------------------------------- where the building is

-- The frontend currently infers the market from the currency, because there
-- is no country field to read. That works only while the two are in lockstep
-- and is reasoning from a proxy: currency is what you pay in, country is
-- where you are. This column deletes marketOf.
--
-- Three statements, not one. The column cannot be born NOT NULL on a table
-- with 130 rows in it unless it has a DEFAULT, and a DEFAULT here would be a
-- lie that outlives the migration: the next cinema inserted would silently
-- become whichever country was convenient today. Add it nullable, state what
-- every existing row is, then close the door.
ALTER TABLE cinema ADD COLUMN country text REFERENCES country(code);

-- The same CASE V18 used for currency and timezone, for the third time and
-- the last. All three are the same fact about where the building is, and
-- after this one the fact has a column of its own to be read from.
UPDATE cinema
   SET country = CASE WHEN state IN ('England', 'Scotland') THEN 'GB'
                      ELSE 'IN'
                 END;

ALTER TABLE cinema ALTER COLUMN country SET NOT NULL;


-- ------------------------------------------------ where a film was released

-- A relationship, not a column on film. A film can be on in both countries at
-- once, so a film.country would force a choice that the world does not make.
--
-- The primary key column order is the decision worth defending. (region,
-- film_id) and (film_id, region) enforce identical uniqueness, but the index
-- behind the key is a btree over the pair, and a btree is only usable for a
-- predicate on its leading column. The only reader is the seeder, and it asks
-- "every film showing in GB", so region leads and that read is an index scan.
-- The reverse question, "which territories is film 412 in", has no caller
-- yet; when it gets one it gets an index of its own, which is a cheaper
-- mistake to fix than a primary key is.
--
-- No surrogate id. The pair is the identity. An id column here would be a
-- unique number nothing ever refers to.
--
-- ON DELETE CASCADE states the intent even though nothing deletes films: a
-- territory row has no meaning without the film it is about. A film that
-- stops playing keeps its row and loses its territories, which is a DELETE
-- from this table and not from film, so its past screenings stay readable.
--
-- No rows seeded here. The data is generated by tools/tmdb_ingest.py and
-- lands in V23, so this file stays a schema migration you can read in one
-- screen.
CREATE TABLE film_region (
    region  text   NOT NULL REFERENCES country(code),
    film_id bigint NOT NULL REFERENCES film(id) ON DELETE CASCADE,

    PRIMARY KEY (region, film_id)
);